def set_cell_shading(cell, color_hex):
    shading = cell._tc.get_or_add_tcPr()
    sh = shading.makeelement(
        qn("w:shd"),
        {qn("w:fill"): color_hex, qn("w:val"): "clear"},
    )
    shading.append(sh)


def add_table(doc, headers, rows, col_widths=None):
    tbl = doc.add_table(
        rows=1 + len(rows), cols=len(headers)
    )
    tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
    tbl.style = "Table Grid"

    for i, h_text in enumerate(headers):
        cell = tbl.rows[0].cells[i]
        cell.text = h_text
        for par in cell.paragraphs:
            for run in par.runs:
                run.bold = True
                run.font.size = Pt(9)
                run.font.color.rgb = RGBColor(255, 255, 255)
        set_cell_shading(cell, "4472C4")

    for ri, row_data in enumerate(rows):
        row = tbl.rows[ri + 1]
        for ci, val in enumerate(row_data):
            row.cells[ci].text = str(val)
            for par in row.cells[ci].paragraphs:
                for run in par.runs:
                    run.font.size = Pt(9)
        if ri % 2 == 1:
            for cell in row.cells:
                set_cell_shading(cell, "D6E4F0")

    if col_widths:
        for i, w in enumerate(col_widths):
            for row in tbl.rows:
                row.cells[i].width = Cm(w)
    return tbl


def photo(doc, filename, caption, max_w=4.8):
    path = os.path.join(PHOTOS, filename)
    if not os.path.exists(path):
        print(f"  SKIP {filename}: not found")
        return False
    fsize = os.path.getsize(path)
    if fsize < 5000:
        print(f"  SKIP {filename}: too small ({fsize})")
        return False
    try:
        from PIL import Image as PILImage
        img = PILImage.open(path)
        w_px, h_px = img.size
        img.close()
        is_portrait = h_px > w_px * 1.2
        width = Inches(3.2 if is_portrait else max_w)
        doc.add_picture(path, width=width)
        doc.paragraphs[-1].alignment = (
            WD_ALIGN_PARAGRAPH.CENTER
        )
        cap = doc.add_paragraph(caption)
        cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
        for run in cap.runs:
            run.italic = True
            run.font.size = Pt(8)
            run.font.color.rgb = RGBColor(0x88, 0x88, 0x88)
        print(f"  OK   {filename} "
              f"({'portrait' if is_portrait else 'landscape'})")
        return True
    except Exception as e:
        print(f"  ERR  {filename}: {e}")
        return False


def h(doc, text, level=1):
    return doc.add_heading(text, level=level)


def p(doc, text):
    par = doc.add_paragraph(text)
    for run in par.runs:
        run.font.size = Pt(10)
    return par


